#!/usr/bin/env python3
"""Ask VOC's driver for its installed model-2 headers and static library."""
from pathlib import Path
import os
import shlex
import shutil
import subprocess
import sys

voc = shutil.which(sys.argv[1])
if not voc:
    raise SystemExit(f"VOC executable not found: {sys.argv[1]}")
build = Path(sys.argv[2]).resolve()
probe = build / "voc-probe"
probe.mkdir(parents=True, exist_ok=True)
name = "VocToolchainProbe"
(probe / (name+".Mod")).write_text(f'MODULE {name}; END {name}.\n')
environment = dict(os.environ, CFLAGS="", LDFLAGS="", LDLIBS="", OBERON=".", MODULES="")
result = subprocess.run([voc, "-O2", "-sFmV", name+".Mod"], cwd=probe,
                        env=environment, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
(probe / "driver.log").write_text(result.stdout)
if result.returncode:
    raise SystemExit("VOC toolchain probe failed:\n"+result.stdout)
command = None
for line in result.stdout.splitlines():
    words = shlex.split(line)
    if name+".c" in words and "-o" in words:
        command = words
        break
if command is None:
    raise SystemExit("VOC did not report its C link command; see "+str(probe / "driver.log"))


def options(flag):
    values = []
    for at, word in enumerate(command):
        if word == flag and at+1 < len(command):
            values.append(command[at+1])
        elif word.startswith(flag) and len(word) > len(flag):
            values.append(word[len(flag):])
    return values


includes = [Path(path).resolve() for path in options("-I")]
headers = next((path for path in includes if (path / "SYSTEM.h").is_file() and (path / "Heap.h").is_file()), None)
archives = [Path(path) / ("lib"+library+".a") for library in options("-l") if library.endswith("-O2")
            for path in options("-L")]
archives += [Path(word) for word in command if word.endswith("-O2.a")]
archive = next((path.resolve() for path in archives if path.is_file()), None)
if headers is None or archive is None:
    raise SystemExit("VOC needs installed model-2 headers and a position-independent static library; see "+str(probe / "driver.log"))
for module in ("XmppItems", "XmppXmlStream", "XmppXmlGen"):
    if not (headers / (module+".h")).is_file():
        raise SystemExit("The VOC installation needs its XML/XMPP libraries: missing "+module+".h")
for path in (headers, archive):
    if any(char in str(path) for char in "\n\r#$"):
        raise SystemExit("Unsupported character in VOC installation path: "+str(path))
text = ("# Generated by VOC toolchain discovery.\n"
        f"VOC_INCLUDE_DIR := {headers}\nVOC_ARCHIVE := {archive}\n")
target = build / "voc-toolchain.mk"
target.write_text(text)
# An included makefile must not stay older than its inputs after a clock change:
# make would otherwise keep rebuilding and rereading it indefinitely.
inputs = [Path(__file__), Path(voc), build / "voc-environment"]
newest = max([target.stat().st_mtime_ns] + [path.stat().st_mtime_ns for path in inputs if path.exists()])
os.utime(target, ns=(target.stat().st_atime_ns, newest))
print(f"Using {voc}: {headers}, {archive}")
